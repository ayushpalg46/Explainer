"""
Markdown Documentation Generator for Explainer.
Generates comprehensive, formatted technical documentation with Mermaid dependency diagrams.
"""
from typing import Dict, Any, List


class MarkdownReporter:
    def generate_report(
        self,
        arch_data: Dict[str, Any],
        compatibility: List[Dict[str, str]],
        file_explanations: List[Dict[str, Any]],
        edges: List[Dict[str, Any]],
        mode: str = "Deterministic Deep Engine"
    ) -> str:
        lines: List[str] = []

        # 1. Header
        lines.append("# Codebase Architecture & Deep Technical Breakdown")
        lines.append(f"> **Generated by Explainer** | Mode: `{mode}` | Total Files: `{arch_data['total_files']}` | Lines of Code: `{arch_data['total_loc']:,}`\n")

        # 2. Architecture Overview
        lines.append("## 1. System Architecture & Tech Stack")
        lines.append(f"**Classification**: `{arch_data['architecture_type']}`  ")
        lines.append(f"{arch_data['architecture_description']}\n")

        lines.append("### Detected Ecosystems")
        lines.append(", ".join(f"`{t}`" for t in arch_data["detected_technologies"]) + "\n")

        lines.append("### Language Distribution")
        lines.append("| Language | Lines of Code | Percentage |")
        lines.append("| :--- | :---: | :---: |")
        tot = arch_data["total_loc"] or 1
        for lang, count in sorted(arch_data["languages"].items(), key=lambda x: -x[1]):
            pct = (count / tot) * 100
            lines.append(f"| **{lang}** | {count:,} | {pct:.1f}% |")
        lines.append("")

        # 3. Compatibility Matrix
        lines.append("### Tech Stack Compatibility & Health Matrix")
        lines.append("| Status | Category | Inspection Check | Details |")
        lines.append("| :---: | :--- | :--- | :--- |")
        for c in compatibility:
            badge = "✅ PASS" if c["status"] == "PASS" else "⚠️ WARN"
            lines.append(f"| {badge} | {c['category']} | **{c['title']}** | {c['details']} |")
        lines.append("")

        # 4. Mermaid Interconnection Diagram
        lines.append("## 2. Cross-File Interconnection Graph")
        lines.append("Visual representation of architectural links, imports, stylesheet cascades, and execution triggers:\n")
        lines.append("```mermaid")
        lines.append("flowchart TD")

        node_ids = {}
        for idx, f in enumerate(file_explanations):
            safe_id = f"N{idx}"
            node_ids[f["header"]["path"]] = safe_id
            clean_name = f["header"]["filename"].replace('"', '')
            lines.append(f'    {safe_id}["{clean_name} ({f["header"]["language"]})"]')

        for e in edges[:40]:  # Limit top 40 for diagram readability
            src_id = node_ids.get(e["from"])
            dst_id = node_ids.get(e["to"])
            if src_id and dst_id:
                rel = e.get("type", "connects")
                lines.append(f"    {src_id} -->|{rel}| {dst_id}")

        lines.append("```\n")

        # 5. Exhaustive Per-File Deep Dives
        lines.append("## 3. Exhaustive Per-File Explanations\n")

        for f in file_explanations:
            h = f["header"]
            p = f["purpose_and_context"]
            conns = f["interconnections"]

            lines.append(f"---")
            lines.append(f"### 📄 `{h['path']}` ({h['language']})")
            lines.append(f"- **Architectural Role**: `{h['role']}`")
            lines.append(f"- **Metrics**: {h['loc']} LOC | {h['size_bytes']} bytes")
            lines.append(f"- **Tech Stack**: {', '.join(p['tech_stack_ecosystem'])}")
            lines.append(f"- **Coupling State**: {conns['coupling_assessment']}\n")

            lines.append(f"#### High-Level Purpose")
            lines.append(f"{p['summary']}\n")
            lines.append(f"{p['architectural_significance']}\n")

            # Concepts
            if f["concepts_and_patterns"]:
                lines.append("#### Architectural Concepts & Design Patterns")
                for cp in f["concepts_and_patterns"]:
                    lines.append(f"- **{cp['concept']}**: {cp['explanation']}")
                lines.append("")

            # Structural breakdown
            if f["components_breakdown"]:
                lines.append("#### Key Structural Components")
                for comp in f["components_breakdown"]:
                    lines.append(f"- **{comp['section']}**: {comp['details']}")
                lines.append("")

            # Symbols breakdown
            if f["symbol_breakdown"]:
                lines.append(f"#### Symbols & Element Catalog ({len(f['symbol_breakdown'])} items)")
                lines.append("| Line | Kind | Symbol / Signature | Purpose & Behavior |")
                lines.append("| :---: | :--- | :--- | :--- |")
                for sym in f["symbol_breakdown"][:40]:
                    clean_sig = sym["signature"].replace("|", "\\|")
                    clean_desc = sym["description"].replace("|", "\\|")
                    lines.append(f"| {sym['line']} | `{sym['kind']}` | `{clean_sig}` | {clean_desc} |")
                if len(f["symbol_breakdown"]) > 40:
                    lines.append(f"| ... | ... | *({len(f['symbol_breakdown']) - 40} additional elements)* | ... |")
                lines.append("")

            # Interconnections
            if conns["outgoing"] or conns["incoming"]:
                lines.append("#### Interconnection Matrix (HOW & WHY)")
                lines.append("| Direction | Target / Source | Relationship | HOW it works | WHY it works (Rationale) |")
                lines.append("| :---: | :--- | :--- | :--- | :--- |")
                for o in conns["outgoing"]:
                    lines.append(f"| OUTGOING ➔ | `{o['target']}` | `{o['relation']}` | {o['how']} | {o['why']} |")
                for i in conns["incoming"]:
                    lines.append(f"| INCOMING ⬅ | `{i['source']}` | `{i['relation']}` | {i['how']} | {i['why']} |")
                lines.append("")

            # Best practices
            if f["best_practices"]:
                lines.append("#### Code Quality & Security Review")
                for bp in f["best_practices"]:
                    lines.append(f"- {bp}")
                lines.append("")

        return "\n".join(lines)
